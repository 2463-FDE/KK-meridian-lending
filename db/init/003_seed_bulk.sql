-- Fail loudly rather than silently seeding fewer offers. The generated block
-- above is one row per funded application, so a count mismatch means the block
-- and the application formulas have diverged -- regenerate, do not patch by
-- hand. The five conditions below are separate on purpose: "180 rows exist" is
-- a much weaker statement than "every one of them is a Model B contract that
-- foots".
DO $$
DECLARE
    expected     int;
    got          int;
    unfooted     int;
    no_schedule  int;
    bad_count    int;
    rate_mismatch int;
BEGIN
    SELECT count(*) INTO expected FROM loans WHERE id BETWEEN 7000 AND 7299;
    SELECT count(*) INTO got FROM offers WHERE app_id BETWEEN 7000 AND 7299;
    IF got <> expected THEN
        RAISE EXCEPTION
          'seed: % funded loans but % offers -- the generated offer block is out '
          'of step with the application formulas. Regenerate it with '
          'python db/tools/regenerate_seed_offers.py --write', expected, got;
    END IF;

    -- 1. the TILA identity: amount financed + finance charge = total of payments
    SELECT count(*) INTO unfooted FROM offers
     WHERE app_id BETWEEN 7000 AND 7299
       AND round(amount_financed + finance_charge, 2) <> round(total_of_payments, 2);
    IF unfooted > 0 THEN
        RAISE EXCEPTION 'seed: % offer(s) do not foot (AF + FC <> total)', unfooted;
    END IF;

    -- 2. every row is a recorded Model B contract, not a bare disclosure
    SELECT count(*) INTO no_schedule FROM offers
     WHERE app_id BETWEEN 7000 AND 7299 AND schedule_version IS NULL;
    IF no_schedule > 0 THEN
        RAISE EXCEPTION 'seed: % offer(s) have no stored schedule', no_schedule;
    END IF;

    -- 3. the payment count agrees with the term (also a CHECK, asserted here so
    --    the seed says which rows rather than failing on the first bad insert)
    SELECT count(*) INTO bad_count FROM offers
     WHERE app_id BETWEEN 7000 AND 7299 AND regular_payment_count + 1 <> term_months;
    IF bad_count > 0 THEN
        RAISE EXCEPTION 'seed: % offer(s) have a payment count that contradicts the term', bad_count;
    END IF;

    -- 4. the total is the SUM OF ACTUAL PAYMENTS, which is what distinguishes
    --    Model B from the model that multiplied an unrounded payment by the term
    SELECT count(*) INTO unfooted FROM offers
     WHERE app_id BETWEEN 7000 AND 7299
       AND round(monthly_payment * regular_payment_count + final_payment, 2)
           <> round(total_of_payments, 2);
    IF unfooted > 0 THEN
        RAISE EXCEPTION
          'seed: % offer(s) whose total is not the sum of their actual payments',
          unfooted;
    END IF;

    -- 5. the offer's note rate is the rate its loan is billed at. loans.apr
    --    holds the CONTRACTUAL rate despite the column name (D19); a mismatch
    --    means the borrower is billed at a rate the disclosure did not price.
    SELECT count(*) INTO rate_mismatch FROM offers o
      JOIN loans l ON l.app_id = o.app_id
     WHERE o.app_id BETWEEN 7000 AND 7299
       AND round(o.note_rate_pct, 3) <> round(l.apr::numeric, 3);
    IF rate_mismatch > 0 THEN
        RAISE EXCEPTION
          'seed: % offer(s) whose note rate differs from the rate their loan bills',
          rate_mismatch;
    END IF;

    RAISE NOTICE 'seed: % Model B offers, all footing.', got;
END $$;

-- Balances: seeded directly, then reconciled by the ledger's opening-balance cutover
-- (ADR 0010 / db/migrations/0035), which records where each seeded balance started.
-- This comment said "single mutable float column (no ledger — debt preserved)": the
-- ledger has existed since 0035, and the columns have been NUMERIC since D12, so the
-- line was wrong twice over.
INSERT INTO balances (loan_id, balance, past_due)
SELECT l.id,
  round((l.principal * (0.30 + ((l.id % 60) / 100.0)))::numeric, 2)::double precision,
  CASE WHEN l.status = 'delinquent' THEN round((50 + (l.id % 400))::numeric, 2)::double precision ELSE 0 END
FROM loans l WHERE l.id BETWEEN 7000 AND 7299;

-- 1..6 payments per loan (~600 rows). Card rows carry last4/brand only. There is
-- no PAN/CVV to populate: the contract migration (db/migrations/0031) dropped
-- those columns and 001_schema.sql stopped creating them, so neither a fresh
-- volume nor a migrated database has them. Nothing wrote them (ADR 0008).
INSERT INTO payments (loan_id, last4, brand, amount, method, created_at)
SELECT l.id,
  CASE WHEN (l.id + s) % 3 = 0 THEN NULL ELSE '1111' END,
  CASE WHEN (l.id + s) % 3 = 0 THEN NULL ELSE 'visa' END,
  round((l.principal / l.term_months)::numeric, 2)::double precision,
  CASE WHEN (l.id + s) % 3 = 0 THEN 'ach' ELSE 'card' END,
  TIMESTAMPTZ '2026-05-01 09:00:00' + ((l.id % 20) || ' days')::interval + (s || ' days')::interval
FROM loans l CROSS JOIN LATERAL generate_series(1, 1 + (l.id % 5)) AS s
WHERE l.id BETWEEN 7000 AND 7299;

-- ---------------------------------------------------------------------------
-- Copy each seeded loan's contractual schedule from its own offer.
-- ---------------------------------------------------------------------------
-- The loan inserts above (and in 002_seed.sql) predate the Model B schedule
-- columns, so on a FRESH database every seeded loan looked like a pre-0030
-- legacy row: servicing hides its note rate because nothing proves the `apr`
-- column holds a contractual rate, and its schedule renders as a
-- reconstruction. The offers are generated with an exact B1 contract, so the
-- proof exists -- it just was not carried across. Migrations are not replayed
-- over fresh init, which is why this belongs here rather than in 0030.
--
-- One statement covering the curated loans (002) and the bulk ones above,
-- keyed on app_id, so a loan can only ever take the schedule of its own offer.
-- Reviewed on PR #10.
UPDATE loans l
   SET regular_payment       = o.monthly_payment,
       regular_payment_count = o.regular_payment_count,
       final_payment         = o.final_payment,
       schedule_version      = o.schedule_version
  FROM offers o
 WHERE o.app_id = l.app_id
   AND o.schedule_version IS NOT NULL
   AND o.regular_payment_count + 1 = l.term_months;

