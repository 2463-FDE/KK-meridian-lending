def test_two_simultaneous_resumes_both_succeed_and_both_stay_recoverable(db):
    """The race the compare-and-swap closes, restated for a stable secret.

    This test used to demand exactly ONE winner. That was the right property
    while the resume token rotated: the loser's caller walked away holding an
    access token whose resume token had been rotated away by its twin, and it
    could never recover -- it had no credential left to try again with. A
    borrower double-submitting their browser needed support.

    With a client-held secret the harm is gone rather than hidden. Both resumes
    match the WHERE clause and both succeed. The access token still rotates, so
    last-write-wins and one caller may hold a stale one -- but that caller
    *still holds the secret*, so it resumes again and gets a live token. An
    unrecoverable state became a retryable one.

    Two real connections, fired at a barrier, because the guarantee is a WHERE
    clause evaluated under a row lock and a single-threaded test cannot observe it.
    """
    import threading

    from app import decision_state, intake

    key = f"concurrent-{uuid.uuid4()}"
    resume = f"client-{uuid.uuid4()}"
    app_id, _, _ = intake.create_application(_payload(key), resume_token=resume)

    barrier = threading.Barrier(2)
    results, errors = [], []

    def _resume():
        try:
            barrier.wait(timeout=10)
            results.append(intake.resume_application(key, resume))
        except intake.ResumeNotAuthorized:
            errors.append("refused")
        except Exception as e:                              # pragma: no cover
            errors.append(repr(e))

    threads = [threading.Thread(target=_resume) for _ in range(2)]
    for t in threads:
        t.start()
    for t in threads:
        t.join(timeout=20)

    assert errors == [], f"a concurrent resume failed: {errors}"
    winners = [r for r in results if r]
    assert len(winners) == 2, "a legitimate concurrent retry was refused"
    assert {w[0] for w in winners} == {app_id}, "the retries recovered different applications"

    # Exactly one access token authenticates -- the writes serialised under the
    # row lock rather than interleaving into a torn state.
    row = _row(db, app_id)
    live = [w for w in winners
            if row["access_token_hash"] == decision_state.hash_access_token(w[1])]
    assert len(live) == 1, (
        "the row does not authenticate exactly one of the two issued access "
        "tokens, so the two rotations interleaved"
    )

    # The point: the caller holding the stale token is not stranded. It has the
    # secret, so it resumes again and gets a token that works.
    recovered = intake.resume_application(key, resume)
    assert recovered is not None
    assert _row(db, app_id)["access_token_hash"] ==         decision_state.hash_access_token(recovered[1])

    # And the secret itself is untouched by any of it.
    assert _row(db, app_id)["resume_token_hash"] ==         decision_state.hash_access_token(resume)


