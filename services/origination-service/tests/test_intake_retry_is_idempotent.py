# --- the lost first response: the failure this whole contract exists for ------

def test_retry_after_a_lost_response_returns_the_same_application(db):
    """The exact reported scenario, end to end."""
    from app import intake

    key = str(uuid.uuid4())
    client_secret = str(uuid.uuid4())

    # First submission commits. Its response is then dropped on the floor --
    # the client learns nothing from it, so the test keeps only the app_id to
    # assert against later, and NOT the tokens.
    first_id, _lost_access, _lost_resume = intake.create_application(
        _payload(key), resume_token=client_secret
    )

    # The retry. The client presents what it has always had: its own secret.
    recovered = intake.resume_application(key, client_secret)

    assert recovered is not None, (
        "the applicant was refused their own in-flight application after a lost "
        "response -- they are now forced to create a duplicate"
    )
    assert recovered[0] == first_id


def test_the_returned_secret_is_the_clients_own_not_a_new_one(db):
    """Rotation would rebuild the hole one attempt later.

    If recovery handed back a NEW secret, the client would have to receive the
    SECOND response to stay recoverable -- the same single point of failure,
    moved. So the value echoed back must be the caller's own.
    """
    from app import intake

    key, secret = str(uuid.uuid4()), str(uuid.uuid4())
    intake.create_application(_payload(key), resume_token=secret)

    _id, _access, returned = intake.resume_application(key, secret)
    assert returned == secret

    # And it still works the next time, and the time after that. A client that
    # loses two responses in a row is not locked out either.
    for _ in range(3):
        again = intake.resume_application(key, secret)
        assert again is not None and again[0] == _id


