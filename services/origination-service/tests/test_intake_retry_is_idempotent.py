def test_the_secret_is_reusable_but_the_access_token_is_not(db):
    """The trade this design makes, asserted in both directions.

    The old test here demanded the resume token be single-use. That property is
    the reason an applicant whose first response was lost could never recover,
    so it is gone on purpose -- and a test asserting a removed property would
    quietly come back as a re-introduction. What replaces it pins BOTH halves:
    the secret keeps working (recovery survives repeated network failure), and
    the access token -- the credential that actually authorises a decision --
    is fresh every time, so a captured one has a bounded life.
    """
    from app import intake

    key = f"reuse-{uuid.uuid4()}"
    secret = f"client-{uuid.uuid4()}"
    _, access1, _ = intake.create_application(_payload(key), resume_token=secret)
    _, access2, _ = intake.create_application(_payload(key), resume_token=secret)
    _, access3, _ = intake.create_application(_payload(key), resume_token=secret)

    assert access1 != access2 != access3, "the access token was not rotated"

    # And the old one is dead: only the newest hash is stored.
    stored = _row(db, intake.resume_application(key, secret)[0])
    from app import decision_state
    assert stored["access_token_hash"] != decision_state.hash_access_token(access1)


